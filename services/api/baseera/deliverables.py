def _t(key: str, locale: str) -> str:
    return TEXT[key]["ar" if locale == "ar" else "en"]


def _localized(value: Any, locale: str, fallback: str = "") -> str:
    if isinstance(value, dict):
        return str(value.get("ar" if locale == "ar" else "en", fallback))
    return str(value) if value is not None else fallback


def build_brief(
    *,
    dataset: dict[str, Any],
    profile: dict[str, Any],
    insights: dict[str, Any],
    cleaning: dict[str, Any] | None = None,
    forecast: dict[str, Any] | None = None,
    locale: str = "en",
    organization: str | None = None,
) -> dict[str, Any]:
    """Assemble the structured brief that every export format renders."""
    ready = locale == "ar"
    quality = profile.get("quality") or {}
    findings = insights.get("findings", [])
    counts = insights.get("counts", {})
    urgent = [f for f in findings if f["severity"] in {"critical", "high"}]

    grade = GRADE_LABEL.get(str(quality.get("grade")), {"en": "—", "ar": "—"})
    if ready:
        headline = (
            f"جرى فحص {ar.count(int(profile.get('row_count', 0)), ar.ROW)} في "
            f"{ar.count(int(profile.get('column_count', 0)), ar.COLUMN)}. "
            f"جودة البيانات {quality.get('score', '—')} من 100 ({grade['ar']}). "
            + (
                f"تستدعي {ar.count(len(urgent), ar.FINDING)} انتباهًا فوريًا."
                if urgent
                else "لا توجد نتيجة تستدعي انتباهًا فوريًا."
            )
        )
    else:
        headline = (
            f"{profile.get('row_count', 0):,} rows across "
            f"{profile.get('column_count', 0):,} columns were examined. "
            f"Data quality scores {quality.get('score', '—')}/100 ({grade['en']}). "
            + (
                f"{len(urgent)} finding requires immediate attention."
                if len(urgent) == 1
                else f"{len(urgent)} findings require immediate attention."
                if urgent
                else "No finding requires immediate attention."
            )
        )

    actions = [
        {
            "severity": f["severity"],
            "source": _localized(f["title"], locale),
            "action": _localized(f["recommendation"], locale),
        }
        for f in findings
        if f["severity"] in {"critical", "high", "medium"}
    ]
    limits = [_localized(f["limitation"], locale) for f in findings]
    if forecast:
        limits.extend(forecast.get("limitations_ar" if ready else "limitations", []))
    if cleaning:
        limits.extend(
            cleaning.get("summary", {}).get("caveats", {}).get("ar" if ready else "en", [])
        )

    return {
        "locale": locale,
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "organization": organization,
        "dataset": dataset,
        "headline": headline,
        "quality": quality,
        "quality_grade": grade["ar"] if ready else grade["en"],
        "profile_summary": {
            "row_count": profile.get("row_count"),
            "column_count": profile.get("column_count"),
            "issues": profile.get("quality_issues", {}),
            "columns": [
                {
                    "name": name,
                    "type": column.get("semantic_type"),
                    "missing": column.get("null_count"),
                    "missing_rate": column.get("missing_rate"),
                    "distinct": column.get("distinct_count"),
                }
                for name, column in profile.get("column_profiles", {}).items()
            ],
        },
        "cleaning": cleaning.get("summary") if cleaning else None,
        "findings": [
            {
                "id": f["id"],
                "kind": f["kind"],
                "severity": f["severity"],
                "severity_label": SEVERITY_LABEL[f["severity"]]["ar" if ready else "en"],
                "confidence": f["confidence"],
                "title": _localized(f["title"], locale),
                "observation": _localized(f["observation"], locale),
                "interpretation": _localized(f["interpretation"], locale),
                "recommendation": _localized(f["recommendation"], locale),
                "limitation": _localized(f["limitation"], locale),
                "evidence": f.get("evidence", {}),
                "chart": f.get("chart"),
            }
            for f in findings
        ],
        "counts": counts,
        "forecast": forecast,
        "actions": actions,
        "limitations": list(dict.fromkeys(limits)),
        "method": {
            "en": (
                "Findings are produced by deterministic statistical rules over the rows "
                "supplied. No language model contributed a number. Re-running the same "
                "dataset version reproduces this brief exactly."
            ),
            "ar": (
                "تُنتَج النتائج بقواعد إحصائية حتمية على الصفوف المزوَّدة. لم يساهم أي "
                "نموذج لغوي في أي رقم. إعادة تشغيل إصدار البيانات نفسه تعيد إنتاج هذا "
                "الموجز حرفيًا."
            ),
        },
    }


